"""Generate docs/species/*.md from the species profiles.

python scripts/generate_species_docs.py          # write the files
python scripts/generate_species_docs.py --check  # exit 1 if they are out of date
"""

from __future__ import annotations

from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from custom_components.mycomonitor.core.species.engine import (  # noqa: E402
    Role,
    SpeciesProfile,
)
from custom_components.mycomonitor.core.species.loader import (  # noqa: E402
    load_profiles,
    load_references,
)

DOCS = ROOT / "docs" / "species"
HEADER = "<!-- Generated by scripts/generate_species_docs.py from the species profiles. -->\n\n"


def curve_text(curve: tuple[tuple[float, float], ...]) -> str:
    return " → ".join(f"{x:g}: {y:g}" for x, y in curve)


def profile_page(profile: SpeciesProfile, references: dict[str, str]) -> str:
    season = profile.season
    lines = [
        HEADER,
        f"# {profile.names.get('es')} / {profile.names.get('en')}\n\n",
        f"*{profile.scientific_name}*\n\n",
        f"{profile.notes}\n\n",
        f"**Habitats:** {', '.join(sorted(profile.habitats))}\n\n",
        "## Season\n\n",
        f"Ramps up from {season.start}, peak {season.peak_start} to {season.peak_end}, ",
        f"ends {season.end}. Evidence grade **{profile.season_grade}**.\n\n",
        f"{profile.season_source}\n\n",
        "## Factors\n\n",
        "| Factor | Indicator | Lag | Role | Weight | Response (value: score) | Grade |\n",
        "|---|---|---|---|---|---|---|\n",
    ]
    for f in profile.factors:
        weight = f"{f.weight:g}" if f.role is Role.SOFT else "–"
        lines.append(
            f"| {f.id} | `{f.indicator}` | {f.lag} d | {f.role.value} | {weight} "
            f"| {curve_text(f.curve)} | {f.grade} |\n"
        )
    lines.append("\n### Rationale\n\n")
    for f in profile.factors:
        refs = f" ({', '.join(f.references)})" if f.references else ""
        lines.append(f"- **{f.id}:** {f.rationale}{refs}\n")
    cited = sorted({*profile.references, *(r for f in profile.factors for r in f.references)})
    lines.append("\n## References\n\n")
    lines += [f"- `{key}`: {references[key]}\n" for key in cited]
    lines.append(
        "\nAll values are configurable (Settings → Devices & services → MycoMonitor → "
        "Configure → Species thresholds). The index is a suitability score, not a probability.\n"
    )
    return "".join(lines)


def index_page(profiles: dict[str, SpeciesProfile]) -> str:
    lines = [
        HEADER,
        "# Species models\n\n",
        "Each model combines a season window, gates (hard limits such as frost) and soft "
        "factors (a weighted geometric mean):\n\n",
        "    index = 100 × season × Π gates × Π soft^(weight / Σ weights)\n\n",
        "Evidence grades A-D are explained in [../science.md](../science.md). Lags mean the "
        "indicator is read that many days earlier, e.g. rain over the 21 days ending 5 days "
        "before.\n\n",
        "| Species | Habitats | Season peak | Weakest grade |\n",
        "|---|---|---|---|\n",
    ]
    for pid, p in profiles.items():
        weakest = max([p.season_grade, *(f.grade for f in p.factors)])
        lines.append(
            f"| [{p.names.get('es')}]({pid}.md) (*{p.scientific_name}*) "
            f"| {', '.join(sorted(p.habitats))} | {p.season.peak_start} – {p.season.peak_end} "
            f"| {weakest} |\n"
        )
    return "".join(lines)


def outputs() -> dict[Path, str]:
    profiles = load_profiles()
    references = load_references()
    files = {DOCS / "README.md": index_page(profiles)}
    for pid, profile in profiles.items():
        files[DOCS / f"{pid}.md"] = profile_page(profile, references)
    return files


def main() -> int:
    check = "--check" in sys.argv
    stale = []
    DOCS.mkdir(parents=True, exist_ok=True)
    for path, text in outputs().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != text:
            stale.append(path.relative_to(ROOT))
            if not check:
                path.write_text(text, encoding="utf-8")
    if check and stale:
        print("Out of date:", *stale, sep="\n  ")
        return 1
    print("Written:" if stale else "Up to date.", *stale, sep="\n  ")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
